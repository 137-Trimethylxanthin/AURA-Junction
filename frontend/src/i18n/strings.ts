export const STRINGS: Record<Lang, Dict> = { en, fr, fi, de }

/** Translate `key` into `lang`, filling `{name}` placeholders from `vars`. Unknown placeholders stay as-is. */
export function t(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  const s = STRINGS[lang][key] ?? STRINGS.en[key]
  if (!vars) return s
  return s.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m))
}

/** "French detected" / "français détecté" … — the language name in the answer's language. */
export function langDetected(lang: Lang, detected: Lang): string {
  const name = t(lang, `lang_${detected}` as StringKey)
  const s = t(lang, 'lang_detected', { lang: name })
  return s.charAt(0).toUpperCase() + s.slice(1)
}
